-- ============================================================
-- 迁移 007：关卡 Flag 随机化（存量部署执行一次即可）
--
-- 背景：种子中的 Flag 是规律字符串（如 flag{html_comment_leak_01}），
-- 看过仓库或掌握命名规律即可猜出，绕过解题直接得分。
-- 本迁移将全部启用关卡的 Flag 替换为 16 位随机 hex。
--
-- 关卡页面已改为通过 app/bootstrap_challenge.php 的
-- xxr_challenge_flag() 动态渲染数据库值，无需同步修改页面。
--
-- 说明：本迁移可重复执行（每次执行都会重新随机化，
-- 已通关记录不受影响，但玩家此前记录的旧 Flag 将失效）。
-- ============================================================

UPDATE `challenges`
SET `flag` = CONCAT('flag{', SUBSTRING(MD5(RAND()), 1, 16), '}')
WHERE `enabled` = 1;
